#!/usr/bin/env node

'use strict';

const fs = require('fs');
const path = require('path');
const { COMMAND_GROUPS } = require('../lib/core/command-manifest');
const en = require('../lib/core/locales/en');
const zh = require('../lib/core/locales/zh');

const ROOT = path.resolve(__dirname, '..');
const START = '<!-- OPENYIDA_COMMANDS_START -->';
const END = '<!-- OPENYIDA_COMMANDS_END -->';

// Every README variant is generated from the same command manifest so the
// human-facing command tables can never drift from the router / --help output.
const TARGETS = [
  {
    file: path.join(ROOT, 'README.md'),
    locale: en,
    tableHeader: '| Command | Description |',
    tableDivider: '|---------|-------------|',
    comment: '<!-- This section is generated by `npm run docs:commands`. Do not edit command rows by hand. -->',
    anchor: 'Run `openyida --help` or `openyida <command> --help` for detailed usage.\n',
    checkError: 'README command docs are out of date. Run `npm run docs:commands`.',
    okMessage: 'README command docs OK',
    missingAnchorError: 'README CLI reference anchor not found',
  },
  {
    file: path.join(ROOT, 'README_zhCN.md'),
    locale: zh,
    tableHeader: '| 命令 | 说明 |',
    tableDivider: '|------|------|',
    comment: '<!-- 本节由 `npm run docs:commands` 自动生成，请勿手动编辑命令行。 -->',
    anchor: '运行 `openyida --help` 或 `openyida <command> --help` 查看详细用法。\n',
    checkError: 'README_zhCN 命令文档已过期，请运行 `npm run docs:commands`。',
    okMessage: 'README_zhCN command docs OK',
    missingAnchorError: 'README_zhCN CLI reference anchor not found',
  },
];

function getByPath(object, keyPath) {
  return String(keyPath || '').split('.').reduce((current, key) => {
    if (!current || typeof current !== 'object') {
      return undefined;
    }
    return current[key];
  }, object);
}

function translate(locale, key) {
  const value = getByPath(locale, key);
  if (!value) {
    console.warn('[generate-command-docs] 缺失翻译，已回退为 key：' + key);
    return key;
  }
  return value;
}

function escapeTableCell(value) {
  return String(value || '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, '<br>');
}

function commandRow(target, entry) {
  return `| \`openyida ${escapeTableCell(entry.usage)}\` | ${escapeTableCell(translate(target.locale, entry.descriptionKey))} |`;
}

function renderGroup(target, group) {
  const commands = group.commands.filter(entry => !entry.hidden);
  if (commands.length === 0) {
    return '';
  }

  return [
    `### ${translate(target.locale, group.titleKey)}`,
    '',
    target.tableHeader,
    target.tableDivider,
    ...commands.map(entry => commandRow(target, entry)),
    '',
  ].join('\n');
}

function renderCommandDocs(target) {
  return [
    START,
    target.comment,
    '',
    ...COMMAND_GROUPS.map(group => renderGroup(target, group)).filter(Boolean),
    END,
  ].join('\n');
}

function replaceGeneratedBlock(target, readme, generated) {
  const startIndex = readme.indexOf(START);
  const endIndex = readme.indexOf(END);

  if (startIndex !== -1 && endIndex !== -1 && endIndex > startIndex) {
    return readme.slice(0, startIndex) + generated + readme.slice(endIndex + END.length);
  }

  const anchorIndex = readme.indexOf(target.anchor);
  if (anchorIndex === -1) {
    throw new Error(target.missingAnchorError);
  }

  const insertIndex = anchorIndex + target.anchor.length;
  return `${readme.slice(0, insertIndex)}\n${generated}\n${readme.slice(insertIndex)}`;
}

function run() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes('--check');
  const printOnly = args.includes('--print');

  if (printOnly) {
    for (const target of TARGETS) {
      process.stdout.write(renderCommandDocs(target) + '\n');
    }
    return;
  }

  let hasError = false;

  for (const target of TARGETS) {
    const generated = renderCommandDocs(target);
    const current = fs.readFileSync(target.file, 'utf8');
    const next = replaceGeneratedBlock(target, current, generated);

    if (checkOnly) {
      if (next !== current) {
        console.error(target.checkError);
        hasError = true;
      } else {
        console.log(target.okMessage);
      }
      continue;
    }

    if (next !== current) {
      fs.writeFileSync(target.file, next);
      console.log(`Updated ${path.basename(target.file)} command docs`);
    } else {
      console.log(`${path.basename(target.file)} command docs already up to date`);
    }
  }

  if (hasError) {
    process.exit(1);
  }
}

run();
